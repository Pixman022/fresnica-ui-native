import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const repositoryRoot = path.resolve(import.meta.dirname, '..', '..');
const sourcePath = path.join(repositoryRoot, 'fresnica-ui', 'design-system', 'tokens.json');
const platformSourcePath = path.join(repositoryRoot, 'fresnica-ui', 'design-system', 'platform-token-source.json');
const outputPath = path.join(import.meta.dirname, '..', 'src', 'generated-token-contract.ts');
if (!fs.existsSync(sourcePath)) {
    throw new Error(`Shared Web token source not found: ${sourcePath}`);
}
if (!fs.existsSync(platformSourcePath)) {
    throw new Error(`Platform token source not found: ${platformSourcePath}`);
}
const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));
const platformSource = JSON.parse(fs.readFileSync(platformSourcePath, 'utf8'));

const primitive = source.primitive ?? {};
const dimension = (group, name, fallback) => {
    const value = primitive[group]?.[name]?.$value ?? fallback;
    const parsed = typeof value === 'string' ? Number.parseFloat(value) : value;
    if (typeof parsed !== 'number' || Number.isNaN(parsed)) {
        throw new Error(`Invalid dimension token ${group}.${name}: ${value}`);
    }
    return parsed;
};

const contract = {
    spacing: {
        xs: dimension('space', 'xs', 4),
        sm: dimension('space', 'sm', 8),
        md: dimension('space', 'md', 12),
        lg: dimension('space', 'lg', 16),
        xl: dimension('space', 'xl', 24),
    },
    radii: {
        sm: dimension('radius', 'sm', 8),
        control: dimension('radius', 'control', 12),
        base: dimension('radius', 'base', 16),
        lg: dimension('radius', 'lg', 24),
        pill: dimension('radius', 'pill', 9999),
    },
    typography: {
        body: dimension('font', 'size-base', 14),
        supporting: dimension('font', 'size-supporting', 13),
        action: dimension('font', 'size-action', 15),
        sectionTitle: dimension('font', 'size-section-title', 18),
        screenTitle: dimension('font', 'size-screen-title', 20),
        display: dimension('font', 'size-display', 48),
    },
    sizes: {
        controlSm: dimension('size', 'control-sm', 32),
        controlCompact: dimension('size', 'control-compact', 36),
        controlBase: dimension('size', 'control-base', 48),
        controlEmphasis: dimension('size', 'control-emphasis', 52),
        controlLg: dimension('size', 'control-lg', 56),
        border: dimension('border', 'width-default', 1),
    },
};

const semanticColorRoles = Object.fromEntries(
    Object.keys(source.semantic?.color ?? {}).map((name) => [name, source.semantic.color[name].$value]),
);

const colorKeys = [
    'background',
    'surface',
    'surfaceRaised',
    'primary',
    'primaryPressed',
    'onPrimary',
    'contentPrimary',
    'contentSecondary',
    'contentMuted',
    'border',
    'separator',
    'positive',
    'negative',
    'warning',
    'overlay',
    'statusBar',
    'navigationBar',
];
const themeColors = platformSource.native?.themeColors;
if (!themeColors?.light || !themeColors?.dark) {
    throw new Error(`Native light/dark theme colors are required in ${platformSourcePath}`);
}
for (const mode of ['light', 'dark']) {
    const missing = colorKeys.filter((name) => typeof themeColors[mode][name] !== 'string');
    if (missing.length > 0) {
        throw new Error(`Missing Native ${mode} color tokens: ${missing.join(', ')}`);
    }
}
const nativeColorRoles = platformSource.native?.semanticRoleMap;
const requiredRoleKeys = [
    'background',
    'surface',
    'primary',
    'contentPrimary',
    'border',
    'positive',
    'negative',
    'warning',
];
if (!nativeColorRoles || typeof nativeColorRoles !== 'object') {
    throw new Error(`Native semantic role mapping is required in ${platformSourcePath}`);
}
const missingRoleKeys = requiredRoleKeys.filter((name) => !nativeColorRoles[name]);
const missingRoleTargets = Object.entries(nativeColorRoles).filter(([, role]) => !semanticColorRoles[role]);
if (missingRoleKeys.length > 0 || missingRoleTargets.length > 0) {
    const details = [
        missingRoleKeys.length > 0 ? `missing keys: ${missingRoleKeys.join(', ')}` : '',
        missingRoleTargets.length > 0
            ? `unknown semantic roles: ${missingRoleTargets.map(([name, role]) => `${name}=${role}`).join(', ')}`
            : '',
    ]
        .filter(Boolean)
        .join('; ');
    throw new Error(`Invalid Native semantic role mapping (${details})`);
}

const contents = `/** Generated by scripts/generate-native-token-contract.mjs. Do not edit manually. */
export const generatedTokens = ${JSON.stringify(contract, null, 4)} as const;

/** Native theme colors generated from the reviewed platform token source. */
export const nativeThemeColors = ${JSON.stringify(themeColors, null, 4)} as const;

/** Native color roles mapped to the shared semantic token names. */
export const nativeColorRoles = ${JSON.stringify(nativeColorRoles, null, 4)} as const;

/** Semantic role aliases remain traceable to the Web token source. */
export const semanticColorRoles = ${JSON.stringify(semanticColorRoles, null, 4)} as const;
`;
fs.writeFileSync(outputPath, contents);
const prettierPath = path.join(import.meta.dirname, '..', 'node_modules', 'prettier', 'bin', 'prettier.cjs');
execFileSync(process.execPath, [prettierPath, '--write', outputPath], { stdio: 'inherit' });
console.log(`Generated ${outputPath} from ${sourcePath} and ${platformSourcePath}`);
